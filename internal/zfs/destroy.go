package zfs

import (
	"context"
	"errors"
	"fmt"

	"github.com/modfin/zdap/internal/zfs/zfsstat"
)

// Destroying used to be done by hand: open the dataset recursively, unmount
// it, ask libzfs for the clones of its snapshots, recurse into those, then
// recurse into the children, then open the dataset a second time and destroy
// it. Each level of that paid two full recursive opens, and Dataset.Clones is
// implemented inside go-libzfs as DatasetOpen(poolName) -- another complete
// recursive open of the pool. So the cost of destroying one clone scaled with
// the size of the whole pool rather than with the subtree being removed, and
// it was paid once per level. On the 34 dataset pool the calibration was done
// against that is ~252 ioctls per level; a pool full of clones makes every
// destroy worse, which is exactly the wrong direction for the clone pool.
//
// `zfs destroy -R` does the same walk inside ZFS: it destroys all dependents
// "including cloned file systems outside the target hierarchy", which is what
// the Clones() recursion was reimplementing. -f forces the unmount that
// UnmountAll did.

// isZdapName reports whether a pool-relative name is something zdap itself
// created, and is therefore zdap's to destroy or write properties on.
//
// This is a guard, not a formality. -R follows dependents out of the target
// hierarchy, so it is the one zfs invocation where a wrong name does damage
// well beyond what was named. Every zdap dataset name is generated by
// GetDatasetBaseNameAt or CloneDataset and matches one of these three
// patterns; anything else under the pool was put there by someone else.
//
// The patterns are anchored on "zdap", which also means a name can never be
// read as a flag by zfs(8).
func isZdapName(name string) bool {
	return IsBaseName(name) || IsSnapName(name) || IsCloneName(name)
}

func checkDestroyTarget(name string) error {
	if name == "" {
		return errors.New("refusing to destroy: no dataset name given")
	}
	if !isZdapName(name) {
		return fmt.Errorf("refusing to destroy %q: not a zdap base, snapshot or clone name", name)
	}
	return nil
}

// Destroy removes a dataset and everything that depends on it: its children,
// its snapshots, and the clones made from those snapshots wherever they live
// on the pool.
//
// The name is relative to the pool, and must be one zdap generated. Destroying
// a dataset that does not exist is an error, as it was before.
func (z *ZFS) Destroy(name string) error {
	return z.destroy(context.Background(), name)
}

func (z *ZFS) destroy(ctx context.Context, name string) error {
	if err := checkDestroyTarget(name); err != nil {
		return err
	}

	path := fmt.Sprintf("%s/%s", z.pool, name)

	z.writeLock()
	defer z.writeUnlock()

	zfsstat.Inc(zfsstat.OpZfsDestroy)

	// -R destroys dependents, including clones outside this hierarchy.
	// -f forces the unmount of anything still mounted.
	stdout, stderr, err := execZfs(ctx, "destroy", "-R", "-f", path)
	if err != nil {
		return fmt.Errorf("could not destroy %s: %w: %s", path, err, zcpMessage(stderr, stdout))
	}
	return nil
}

// DestroyAll removes every dataset zdap has created on the pool.
//
// It destroys the bases first, because -R takes each base's snapshots and the
// clones made from them with it, and then sweeps up whatever clones are left.
//
// Unlike the recursive walk this replaces, it destroys only datasets whose
// names zdap generated. A dataset someone else put under the pool is left
// alone and reported, rather than being destroyed along with everything else.
//
// A failure on one dataset does not stop the rest: this is a cleanup command,
// and stopping halfway through leaves more behind than carrying on does. All
// the failures come back together.
func (z *ZFS) DestroyAll() error {
	ctx := context.Background()

	lst, err := z.Load(ctx)
	if err != nil {
		return fmt.Errorf("could not list %s: %w", z.pool, err)
	}

	var errs []error
	destroy := func(name string) {
		fmt.Println(" - Destroying", name)
		if err := z.destroy(ctx, name); err != nil {
			errs = append(errs, err)
		}
	}

	for _, name := range lst.Bases() {
		destroy(name)
	}

	// Reloaded rather than reused: the pass above has removed most of these
	// already, and destroying a clone that is gone is an error.
	lst, err = z.Load(ctx)
	if err != nil {
		return errors.Join(append(errs, fmt.Errorf("could not list %s: %w", z.pool, err))...)
	}
	for _, name := range lst.namesMatching(IsCloneName) {
		destroy(name)
	}

	for _, name := range lst.Names() {
		if !isZdapName(name) {
			fmt.Println(" - Leaving", name, "alone: not a dataset zdap created")
		}
	}

	return errors.Join(errs...)
}
